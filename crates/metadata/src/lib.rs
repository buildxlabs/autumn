//! Catalog metadata from AniList's public GraphQL API.
//!
//! [`AniList`] sends its queries through `net`'s shared [`net::Client`], so
//! every call shares AniList's rate limiter and lockouts. Results are plain
//! types that name media by AniList id; callers map them to a
//! [`domain::MediaId`] through `db`. [`CatalogCache`] serves them from
//! disk first, refreshing stale ones. See ARCHITECTURE §2. This is a back-end
//! crate: no GPUI.

mod cache;
mod catalog;
mod client;
mod detail;
mod error;
mod fragments;
mod model;
mod search;
mod viewer;

pub use cache::{AIRING_TTL, CATALOG_TTL, Cached, CatalogCache, Load, Lookup, Refresh};
pub use catalog::{AiringEpisode, CountryTrends, HomeLoad};
pub use client::{ANILIST_ENDPOINT, AniList};
pub use error::Error;
pub use model::{
    Character, CharacterRole, MediaDetail, MediaFormat, MediaRelation, MediaSeason, MediaStatus,
    MediaSummary, MediaTitle, Relation, VoiceActor,
};
pub use search::{MediaSort, PageRequest, SearchFilters, SearchPage};
pub use viewer::{Avatar, Viewer};

/// The AniList schema, registered in `build.rs` from `schema/anilist.graphql`.
#[cynic::schema("anilist")]
#[expect(
    unreachable_pub,
    missing_debug_implementations,
    reason = "marker types generated by cynic for every schema type"
)]
mod schema {}
